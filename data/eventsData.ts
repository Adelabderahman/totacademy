export function getTranslation(key: string, lang: Language): string {
  if (coreI18n[lang] && coreI18n[lang][key] !== undefined) {
    return coreI18n[lang][key];
  }
  return coreI18n.ar[key] || key;
}

export function getLocalized(value: LocalizedString | string, lang: Language): string {
  if (value && typeof value === 'object') {
    return value[lang] || value.ar || '';
  }
  return String(value || '');
}

export function formatEventDate(dateString: string, lang: Language): string {
  const locale = lang === 'ar' ? 'ar-DZ' : lang === 'fr' ? 'fr-FR' : 'en-GB';
  try {
    return new Intl.DateTimeFormat(locale, {
      weekday: 'short',
      day: 'numeric',
      month: 'short',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    }).format(new Date(dateString));
  } catch {
    return dateString;
  }
}
